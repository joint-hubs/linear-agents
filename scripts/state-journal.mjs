#!/usr/bin/env node
// scripts/state-journal.mjs — the per-task journal: docs/state/<TASK-ID>.md (FOC-904).
//
//   node scripts/state-journal.mjs init [--task <id>]
//   node scripts/state-journal.mjs add --text "<entry>" [--task <id>]
//   node scripts/state-journal.mjs set --field PR=<value> [--field Status=<value>] [--task <id>]
//
// WHY per task: docs/STATE.md is one shared, hand-written journal — two
// Supervisors working the same repo collide on it by construction. A journal
// PER TASK has no shared writable surface: every session appends only to its
// own file, and the one thing that aggregates them (the index block in
// STATE.md) is generated by scripts/state-index.mjs, never written by hand.
//
// The task id comes from --task, else LA_TASK_ID (set by the task session
// host); session and run come from FENIX_SUPERVISOR_SESSION_ID and
// LA_SUPERVISOR_RUN. No id resolvable → exit 2: a journal without a task
// identity is exactly the ambiguity this tool exists to remove.
//
// The file is append-only for entries: `add` writes below the last heading and
// never rewrites a byte above it; `set` touches only the named metadata line
// in the header block. Docs: docs/task-journals.md.

import { existsSync, readFileSync, writeFileSync } from "node:fs";
import { dirname, join, resolve } from "node:path";
import { fileURLToPath, pathToFileURL } from "node:url";
import { spawnSync } from "node:child_process";

const METADATA_KEYS = ["Task", "Session", "Run", "Branch", "PR", "Status"];

/** The root whose docs/ the journals live under: LA_ROOT, else this repo. */
export function resolveRoot(env = process.env) {
  if (env.LA_ROOT) return resolve(env.LA_ROOT);
  return resolve(dirname(fileURLToPath(import.meta.url)), "..");
}

/** A task id is also a filename — refuse anything that could climb out of docs/state/. */
export function sanitizeTaskId(id) {
  if (!id || !/^[A-Za-z0-9][A-Za-z0-9._-]*$/.test(id)) return null;
  return id;
}

export function journalPath(root, taskId) {
  return join(root, "docs", "state", `${taskId}.md`);
}

/** Local wall-clock stamp used in entry headings: YYYY-MM-DD HH:MM. */
export function formatStamp(date = new Date()) {
  const pad = (n) => String(n).padStart(2, "0");
  return (
    `${date.getFullYear()}-${pad(date.getMonth() + 1)}-${pad(date.getDate())} ` +
    `${pad(date.getHours())}:${pad(date.getMinutes())}`
  );
}

/** The git branch of `root`, or "-" when git cannot say (not a repo / bare dir). */
function currentBranch(root) {
  try {
    const res = spawnSync("git", ["rev-parse", "--abbrev-ref", "HEAD"], {
      cwd: root,
      encoding: "utf8",
    });
    const name = (res.stdout || "").trim();
    return res.status === 0 && name ? name : "-";
  } catch {
    return "-";
  }
}

/**
 * Create the journal file with its metadata block. A second init is a no-op:
 * the file is the task's record, and re-deriving the header could rewrite
 * history the metadata block already holds (Branch, PR, Status).
 */
export function initJournal({ root, taskId, sessionId = "-", runId = "-", branch = null }) {
  const path = journalPath(root, taskId);
  if (existsSync(path)) return { path, created: false };
  const header =
    `# ${taskId} — journal\n` +
    `\n` +
    `Task: ${taskId}\n` +
    `Session: ${sessionId || "-"}\n` +
    `Run: ${runId || "-"}\n` +
    `Branch: ${branch || "-"}\n` +
    `PR: -\n` +
    `Status: in progress\n`;
  writeFileSync(path, header, "utf8");
  return { path, created: true };
}

/**
 * Append one entry. Heading: `## <YYYY-MM-DD HH:MM> — <first line>`; the rest
 * of the text is the body. Only ever appends — earlier content is read to
 * build the tail but never rewritten.
 */
export function addEntry({ root, taskId, text, stamp = formatStamp() }) {
  const path = journalPath(root, taskId);
  if (!existsSync(path)) {
    throw new Error(`no journal for ${taskId} — run "state-journal.mjs init" first`);
  }
  const lines = String(text ?? "").replace(/\r\n/g, "\n").split("\n");
  const first = lines[0].trim();
  const rest = lines
    .slice(1)
    .join("\n")
    .replace(/\n+$/, "")
    .trim();
  if (!first) throw new Error("--text is empty");
  const entry = `## ${stamp} — ${first}\n${rest ? `\n${rest}\n` : ""}\n`;
  const existing = readFileSync(path, "utf8");
  writeFileSync(path, existing + entry, "utf8");
  return { path, heading: `## ${stamp} — ${first}` };
}

/**
 * Update metadata lines (Task/Session/Run/Branch/PR/Status) IN PLACE. The edit
 * is confined to the header block — the region before the first `## ` entry
 * heading — so an entry can never be altered through this verb.
 */
export function setFields({ root, taskId, fields }) {
  const path = journalPath(root, taskId);
  if (!existsSync(path)) {
    throw new Error(`no journal for ${taskId} — run "state-journal.mjs init" first`);
  }
  const text = readFileSync(path, "utf8");
  const firstHeading = text.search(/^## /m);
  const headEnd = firstHeading === -1 ? text.length : firstHeading;
  const head = text.slice(0, headEnd);
  const tail = text.slice(headEnd);

  let updated = head;
  const applied = [];
  for (const field of fields) {
    const eq = field.indexOf("=");
    const key = eq === -1 ? field : field.slice(0, eq);
    const value = eq === -1 ? "" : field.slice(eq + 1);
    if (!METADATA_KEYS.includes(key)) {
      throw new Error(`unknown field "${key}" — one of: ${METADATA_KEYS.join(", ")}`);
    }
    if (/[\r\n]/.test(value)) throw new Error(`value for ${key} must be a single line`);
    const line = new RegExp(`^${key}: .*$`, "m");
    if (!line.test(updated)) {
      throw new Error(`no "${key}:" line in the metadata block of ${taskId}`);
    }
    // Replacement FUNCTION: a string replacement would interpret `$&`/`$1`
    // in the value — a literal `PR: $& $1 X` must be stored as written.
    updated = updated.replace(line, () => `${key}: ${value}`);
    applied.push({ key, value });
  }
  writeFileSync(path, updated + tail, "utf8");
  return { path, applied };
}

function usage(stream) {
  stream(
    "Usage: node scripts/state-journal.mjs init [--task <id>]\n" +
      "       node scripts/state-journal.mjs add --text \"<entry>\" [--task <id>]\n" +
      "       node scripts/state-journal.mjs set --field <Key>=<value> [--task <id>]\n" +
      "  Task id: --task, else LA_TASK_ID. Session/run: FENIX_SUPERVISOR_SESSION_ID / LA_SUPERVISOR_RUN.",
  );
}

/** Parse the hand-rolled argv shared by all three verbs. Returns null on a usage error (already reported). */
export function parseArgv(argv, { stderr = console.error } = {}) {
  const opts = { verb: null, task: null, text: null, fields: [] };
  for (let i = 0; i < argv.length; i++) {
    const a = argv[i];
    if (a === "--help" || a === "-h") {
      usage(console.log);
      return { help: true };
    } else if (a === "--task" && i + 1 < argv.length) {
      opts.task = argv[++i];
    } else if (a === "--text" && i + 1 < argv.length) {
      opts.text = argv[++i];
    } else if (a === "--field" && i + 1 < argv.length) {
      opts.fields.push(argv[++i]);
    } else if (a === "init" || a === "add" || a === "set") {
      opts.verb = a;
    } else {
      stderr(`state-journal: unknown argument "${a}"`);
      usage(stderr);
      return null;
    }
  }
  if (!opts.verb) {
    stderr("state-journal: a verb is required (init | add | set)");
    usage(stderr);
    return null;
  }
  if (opts.verb === "add" && opts.text === null) {
    stderr('state-journal: add needs --text "<entry>"');
    return null;
  }
  if (opts.verb === "set" && !opts.fields.length) {
    stderr("state-journal: set needs at least one --field <Key>=<value>");
    return null;
  }
  return opts;
}

/**
 * The CLI. Returns the process exit code instead of exiting, so tests (and the
 * merge node) can drive it in-process; the main guard below exits for real.
 */
export function runCli(argv, { env = process.env, stdout = console.log, stderr = console.error, root = null } = {}) {
  const opts = parseArgv(argv, { stderr });
  if (!opts) return 2;
  if (opts.help) return 0;

  const taskId = sanitizeTaskId(opts.task ?? env.LA_TASK_ID);
  if (!taskId) {
    stderr("state-journal: no task id — pass --task <id> or set LA_TASK_ID");
    return 2;
  }
  const base = root ?? resolveRoot(env);
  try {
    if (opts.verb === "init") {
      const res = initJournal({
        root: base,
        taskId,
        sessionId: env.FENIX_SUPERVISOR_SESSION_ID || "-",
        runId: env.LA_SUPERVISOR_RUN || "-",
        branch: currentBranch(base),
      });
      stdout(`journal: ${res.path} ${res.created ? "created" : "already exists — left untouched"}`);
      return 0;
    }
    if (opts.verb === "add") {
      const res = addEntry({ root: base, taskId, text: opts.text });
      stdout(`journal: ${res.path} appended "${res.heading}"`);
      return 0;
    }
    const res = setFields({ root: base, taskId, fields: opts.fields });
    for (const f of res.applied) stdout(`journal: ${res.path} ${f.key}: ${f.value}`);
    return 0;
  } catch (err) {
    stderr(`state-journal: ${err.message}`);
    return 1;
  }
}

const isMain = process.argv[1] && import.meta.url === pathToFileURL(process.argv[1]).href;
if (isMain) {
  process.exit(runCli(process.argv.slice(2)));
}
